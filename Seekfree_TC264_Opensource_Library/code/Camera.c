//  Sample usage:   uint8 thr = Camera_OTSU_GetThreshold(Image_Use, LCDW, LCDH);
//-------------------------------------------------------------------------------
uint8 Camera_OTSU_GetThreshold(uint8 *image[][LCDW], uint16 col, uint16 row)
{
    #define GRAY_SCALE  256                     // ?????(0-255)
    uint16 width  = col;
    uint16 height = row;
    uint32 pixelSum;                             // ?????
    uint32 pixelCount[GRAY_SCALE];               // ???????????
    float  pixelPro[GRAY_SCALE];                 // ???????????
    uint32 gray_sum = 0;                         // ????????
    uint8  threshold = 0;                        // ??????
    uint16 i, j;

    /* ---- ?????????? ---- */
    pixelSum = (uint32)width * height;

    /* ---- ???????? ---- */
    for (i = 0; i < GRAY_SCALE; i++)
    {
        pixelCount[i] = 0;
        pixelPro[i]  = 0.0f;
    }

    /* ---- ?????????(0-255)????????????? ---- */
    for (i = 0; i < height; i++)
    {
        for (j = 0; j < width; j++)
        {
            uint8 gray_val = *image[i][j];
            pixelCount[gray_val]++;              // ???
            gray_sum += gray_val;
        }
    }

    /* ---- ?????????????????????????? ---- */
    for (i = 0; i < GRAY_SCALE; i++)
    {
        pixelPro[i] = (float)pixelCount[i] / (float)pixelSum;
    }

    /* ---- OTSU????? ---- */
    {
        float w0 = 0.0f, w1 = 0.0f;              // ?????????
        float u0tmp = 0.0f, u1tmp = 0.0f;        // ????????
        float u0, u1, u;                         // ????????, ????????, ??????
        float deltaTmp, deltaMax = 0.0f;
        float gray_avg;                           // ????????
        uint8  jj;

        gray_avg = (float)gray_sum / (float)pixelSum;

        for (jj = 0; jj < GRAY_SCALE; jj++)
        {
            w0    += pixelPro[jj];               // ????????
            u0tmp += (float)jj * pixelPro[jj];

            /* ---- w0=0 ?? w1=0 ???? ---- */
            if (w0 < 1e-6f || (1.0f - w0) < 1e-6f)
            {
                continue;
            }

            w1    = 1.0f - w0;
            u1tmp = gray_avg - u0tmp;

            u0    = u0tmp / w0;                  // ???????
            u1    = u1tmp / w1;                  // ???????
            u     = u0tmp + u1tmp;               // ???????

            /* ---- ???? = w0*(u0-u)^2 + w1*(u1-u)^2 ---- */
            deltaTmp = w0 * (u0 - u) * (u0 - u) + w1 * (u1 - u) * (u1 - u);

            if (deltaTmp > deltaMax)
            {
                deltaMax  = deltaTmp;
                threshold = jj;
            }
            /*
             * ???????????? (?????????, ???????)
             * ???????????? break, ???????
             */
            else if (deltaTmp < deltaMax)
            {
                break;
            }
        }
    }

    return threshold;
}

